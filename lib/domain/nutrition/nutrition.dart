  }

  final String id;
  final String tenantId;
  final String mealPlanId;
  final int dayNumber;
  final String breakfast;
  final String lunch;
  final String dinner;
  final String? snacks;
  final int caloriesKcal;
  final DateTime createdAt;
  final DateTime updatedAt;
}

